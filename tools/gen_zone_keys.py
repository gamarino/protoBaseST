#!/usr/bin/env python3
"""Generate src/protobase/zonekeys.st, protoBaseST's pinned list of IANA time-zone keys.

protoBaseST has no time-zone database (design section 4.3). A zone key is valid when it is in
this list: the Zone and Link names of one IANA tzdata release, read from that release's
``tzdata.zi`` (the compact form that ``zic`` reads; IANA's own Makefile builds it, and
distributions install it as /usr/share/zoneinfo/tzdata.zi), backward links included, as
ZoneInfo accepts them wherever the compiled files exist. Excluded: ``Factory`` (a
placeholder zone, not a place) and the host-relative names ``localtime`` and ``posixrules``,
which are not in tzdata.zi anyway.

Usage:
    tools/gen_zone_keys.py <path to tzdata.zi> <expected release, e.g. 2026e>

The script refuses a file whose ``# version`` line names another release, so the release
recorded in the output is the release read. Regenerate the list deliberately (a new release
adds keys; a key newer than the pinned release is refused explicitly) and commit the result.
"""
import hashlib
import sys

EXCLUDED = {"Factory", "localtime", "posixrules"}


def main(argv):
    if len(argv) != 3:
        sys.exit(__doc__)
    path, expected = argv[1], argv[2]
    data = open(path, "rb").read()
    lines = data.decode("utf-8").splitlines()
    version = lines[0].split()[-1] if lines and lines[0].startswith("# version ") else None
    if version != expected:
        sys.exit(f"{path} is tzdata {version!r}, not {expected!r}")
    keys = set()
    for line in lines:
        parts = line.split()
        if not parts:
            continue
        if parts[0] == "Z":
            keys.add(parts[1])
        elif parts[0] == "L":
            keys.add(parts[2])
    keys -= EXCLUDED
    for key in keys:
        if "'" in key or not key.isascii():
            sys.exit(f"unexpected key {key!r}")
    digest = hashlib.sha256(data).hexdigest()
    out = []
    out.append(f'"-- zonekeys.st: the IANA time-zone keys of tzdata {version} (GENERATED, do not edit) --\n')
    out.append(f"Generated by tools/gen_zone_keys.py from tzdata.zi of release {version}")
    out.append(f"(sha256 {digest}): {len(keys)} Zone and Link names,")
    out.append("Factory excluded. protoBaseST has no time-zone database (design 4.3); this list is its")
    out.append("database of keys: a key outside it is refused (PBCorruptionError when read,")
    out.append('PBValidationError when written), identically on every machine."\n')
    out.append("Object subclass: #PBZoneKeys classVariableNames: 'Keys'.\n")
    out.append("\"The tzdata release the list was generated from.\"")
    out.append("PBZoneKeys class >> release")
    out.append(f"  ^ '{version}'.\n")
    out.append("\"True when aKey is one of the pinned IANA keys.\"")
    out.append("PBZoneKeys class >> includes: aKey")
    out.append("  ^ (aKey isString and: [aKey isSymbol not]) and: [Keys includes: aKey].\n")
    out.append("PBZoneKeys class >> size")
    out.append("  ^ Keys size.\n")
    out.append("PBZoneKeys class >> _initializeKeys")
    out.append("  | set |")
    out.append("  Keys isNil ifFalse: [^ Keys].")
    out.append("  set := Set new.")
    out.append("  self _keyList do: [:each | set add: each].")
    out.append("  Keys := set.")
    out.append("  ^ Keys.\n")
    out.append("PBZoneKeys class >> _keyList")
    out.append("  ^ #(")
    for key in sorted(keys):
        out.append(f"    '{key}'")
    out.append("  ).\n")
    out.append("PBZoneKeys _initializeKeys.")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv)
